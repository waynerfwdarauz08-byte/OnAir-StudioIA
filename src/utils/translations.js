export function translateInterface(text, language = "es", values = {}) {
  if (typeof text !== "string") return text;
  let translated = language === "en" ? interfaceTranslations[text] || text : reverseTranslations[text] || text;
  if (translated === text) {
    for (const pattern of dynamicTranslations) {
      const match = pattern[language === "en" ? "esRegex" : "enRegex"].exec(text);
      if (match) {
        translated = pattern[language === "en" ? "en" : "es"].replace(/\{(\w+)\}/g, (token, key) => {
          const value = match[pattern.keys.indexOf(key) + 1] ?? token;
          return pattern.es.startsWith("El resultado se generó,") ? translateInterface(value, language) : value;
        });
        break;
      }
    }
  }
  return translated.replace(/\{(\w+)\}/g, (match, key) => Object.hasOwn(values, key) ? String(values[key]) : match);
}

const reverseTranslations = Object.fromEntries(Object.entries(interfaceTranslations).map(([es, en]) => [en, es]));
function templateRegex(text) {
  return new RegExp("^" + text.split(/(\{\w+\})/).map((part) => /^\{\w+\}$/.test(part) ? "([\\s\\S]*?)" : part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("") + "$");
}
const dynamicTranslations = Object.entries(interfaceTranslations).filter(([es]) => /\{\w+\}/.test(es)).map(([es, en]) => ({
  es, en, keys: [...es.matchAll(/\{(\w+)\}/g)].map((match) => match[1]), esRegex: templateRegex(es), enRegex: templateRegex(en),
}));
